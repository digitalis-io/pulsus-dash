/**
 * Generates `src/styles/tokens.css`, `src/styles/tokens.ts` and the engine's
 * `engine/crates/dash-tokens/src/tokens.rs` from `../design/tokens.toml` (VL-001, VL-021, T08-022,
 * T01-010). `tokens.ts` also carries `seriesPalette` and `sequentialRamp`, the `series-N` and
 * `ramp-N` colours of each theme as ordered arrays for the chart engine (T02-004); `tokens.rs`
 * carries every token, colours as sRGB-encoded `Rgba8` bytes equal to the CSS hex (T08 §4.7).
 * `font.tracking` is signed letter spacing in em (within ±0.05, `--tracking-*`); `elevation` and
 * `material` are string tables (`--elevation-*`, `--material-*`; #282).
 * `--check` compares in memory instead of writing (`ci:token-lint`).
 *
 * Exit: 0 written or up to date, 1 stale generated file, 2 unreadable or invalid tokens.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'smol-toml';
import { InputError, report, type Finding } from './lib/report.ts';

export const CLIENT_ROOT = fileURLToPath(new URL('..', import.meta.url));
export const TOKENS_TOML = join(CLIENT_ROOT, '..', 'design', 'tokens.toml');
export const TOKENS_CSS = join(CLIENT_ROOT, 'src', 'styles', 'tokens.css');
export const TOKENS_TS = join(CLIENT_ROOT, 'src', 'styles', 'tokens.ts');
export const TOKENS_RS = join(
  CLIENT_ROOT,
  '..',
  'engine',
  'crates',
  'dash-tokens',
  'src',
  'tokens.rs',
);

const HEADER = 'Generated by scripts/gen-tokens.ts from design/tokens.toml. Do not edit.';
const COLOUR = /^#[0-9A-F]{6}(?:[0-9A-F]{2})?$/;
const SAFE_TEXT = /^[^;{}<>\\]+$/;
const NAME = /^[a-z0-9][a-z0-9-]*$/;
/** The largest letter spacing magnitude a `font.tracking` token may have (em). */
const TRACKING_MAX = 0.05;

type Table = Record<string, unknown>;

/** Numeric tables: TOML path → CSS custom property prefix and unit. */
const NUMERIC: readonly { path: string; prefix: string; unit: string }[] = [
  { path: 'space', prefix: 'space', unit: 'px' },
  { path: 'size', prefix: 'size', unit: 'px' },
  { path: 'border', prefix: 'border', unit: 'px' },
  { path: 'font.size', prefix: 'font-size', unit: 'px' },
  { path: 'font.weight', prefix: 'font-weight', unit: '' },
  { path: 'font.advance', prefix: 'font-advance', unit: '' },
  { path: 'line-height', prefix: 'line-height', unit: '' },
  { path: 'opacity', prefix: 'opacity', unit: '' },
];

export interface Tokens {
  colour: { dark: Record<string, string>; light: Record<string, string> };
  space: Record<string, number>;
  size: Record<string, number>;
  radius: Record<string, number>;
  /** Alphas, 0..1 (T25-006). */
  opacity: Record<string, number>;
  border: Record<string, number>;
  font: {
    family: Record<string, string>;
    size: Record<string, number>;
    weight: Record<string, number>;
    /** Glyph advance in em (the monospace advance measures axis labels, T02 §4.5). */
    advance: Record<string, number>;
    /** Letter spacing in em, signed, within ±0.05 (#282). */
    tracking: Record<string, number>;
    lineHeight: Record<string, number>;
  };
  /** Box shadows, in stacking order (VL-004 as amended). */
  elevation: Record<string, string>;
  /** Material values: the backdrop filter (VL-017 as amended). */
  material: Record<string, string>;
  motion: Record<string, number | string>;
}

/** Numbered colour families emitted as ordered arrays: TOML key prefix → export name. */
const PALETTES: readonly { prefix: string; name: string }[] = [
  { prefix: 'series', name: 'seriesPalette' },
  { prefix: 'ramp', name: 'sequentialRamp' },
];

function isTable(v: unknown): v is Table {
  return typeof v === 'object' && v !== null && !Array.isArray(v) && !(v instanceof Date);
}

function table(root: Table, path: string): Table {
  let v: unknown = root;
  for (const part of path.split('.')) {
    v = isTable(v) ? v[part] : undefined;
  }
  if (!isTable(v)) throw new InputError(`missing table [${path}]`);
  return v;
}

function checkName(path: string, key: string): void {
  if (!NAME.test(key)) throw new InputError(`invalid token name ${path}.${key}`);
}

function numbers(root: Table, path: string): Record<string, number> {
  const out: Record<string, number> = {};
  for (const [k, v] of Object.entries(table(root, path))) {
    checkName(path, k);
    if (typeof v !== 'number' || !Number.isFinite(v) || v < 0) {
      throw new InputError(`invalid value for ${path}.${k}: expected a non-negative number`);
    }
    out[k] = v;
  }
  return out;
}

function tracking(root: Table, path: string): Record<string, number> {
  const out: Record<string, number> = {};
  for (const [k, v] of Object.entries(table(root, path))) {
    checkName(path, k);
    if (typeof v !== 'number' || !Number.isFinite(v) || Math.abs(v) > TRACKING_MAX) {
      throw new InputError(
        `invalid value for ${path}.${k}: expected em within ±${String(TRACKING_MAX)}`,
      );
    }
    out[k] = v;
  }
  return out;
}

function colours(root: Table, path: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(table(root, path))) {
    checkName(path, k);
    if (typeof v !== 'string' || !COLOUR.test(v)) {
      throw new InputError(
        `invalid value for ${path}.${k}: expected uppercase #RRGGBB or #RRGGBBAA`,
      );
    }
    out[k] = v;
  }
  return out;
}

function texts(root: Table, path: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [k, v] of Object.entries(table(root, path))) {
    checkName(path, k);
    if (typeof v !== 'string' || !SAFE_TEXT.test(v)) {
      throw new InputError(`invalid value for ${path}.${k}: expected text without ; { } < > \\`);
    }
    out[k] = v;
  }
  return out;
}

/**
 * The `<prefix>-1`, `<prefix>-2`, … colours in numeric order. Throws `InputError` naming the first
 * missing key when the numbering is not contiguous from 1.
 */
function ordered(c: Record<string, string>, prefix: string): string[] {
  const re = new RegExp(`^${prefix}-(\\d+)$`);
  const numbers = Object.keys(c)
    .map((k) => re.exec(k)?.[1])
    .filter((n): n is string => n !== undefined)
    .map(Number)
    .sort((a, b) => a - b);
  return numbers.map((n, i) => {
    const key = `${prefix}-${String(i + 1)}`;
    if (n !== i + 1) throw new InputError(`${prefix}-N must be contiguous from 1: missing ${key}`);
    return c[key] ?? '';
  });
}

/** Parses and validates the TOML text. Throws `InputError` naming the offending key. */
export function parseTokens(tomlText: string): Tokens {
  let root: Table;
  try {
    root = parse(tomlText);
  } catch (e) {
    throw new InputError(
      `tokens.toml does not parse: ${e instanceof Error ? e.message : String(e)}`,
    );
  }
  const known = new Set([
    'color',
    'space',
    'size',
    'radius',
    'opacity',
    'border',
    'font',
    'line-height',
    'elevation',
    'material',
    'motion',
  ]);
  for (const k of Object.keys(root))
    if (!known.has(k)) throw new InputError(`unknown table [${k}]`);

  const dark = colours(root, 'color.dark');
  const light = colours(root, 'color.light');
  const darkKeys = Object.keys(dark).sort().join(',');
  if (darkKeys !== Object.keys(light).sort().join(',')) {
    throw new InputError('color.dark and color.light must define the same keys');
  }

  for (const { prefix } of PALETTES) ordered(dark, prefix);

  const motion: Record<string, number | string> = {};
  for (const [k, v] of Object.entries(table(root, 'motion'))) {
    checkName('motion', k);
    if (typeof v === 'number' && Number.isFinite(v) && v >= 0) motion[k] = v;
    else if (typeof v === 'string' && SAFE_TEXT.test(v)) motion[k] = v;
    else throw new InputError(`invalid value for motion.${k}: expected ms or an easing function`);
  }

  return {
    colour: { dark, light },
    space: numbers(root, 'space'),
    size: numbers(root, 'size'),
    radius: numbers(root, 'radius'),
    opacity: numbers(root, 'opacity'),
    border: numbers(root, 'border'),
    font: {
      family: texts(root, 'font.family'),
      size: numbers(root, 'font.size'),
      weight: numbers(root, 'font.weight'),
      advance: numbers(root, 'font.advance'),
      tracking: tracking(root, 'font.tracking'),
      lineHeight: numbers(root, 'line-height'),
    },
    elevation: texts(root, 'elevation'),
    material: texts(root, 'material'),
    motion,
  };
}

function block(selector: string, decls: Record<string, string>, indent = ''): string {
  const lines = Object.keys(decls)
    .sort()
    .map((k) => `${indent}  ${k}: ${decls[k] ?? ''};`);
  return `${indent}${selector} {\n${lines.join('\n')}\n${indent}}\n`;
}

function colourDecls(c: Record<string, string>): Record<string, string> {
  return Object.fromEntries(Object.entries(c).map(([k, v]) => [`--${k}`, v]));
}

export function generateCss(tk: Tokens, root: Table): string {
  const common: Record<string, string> = {};
  for (const { path, prefix, unit } of NUMERIC) {
    for (const [k, v] of Object.entries(numbers(root, path)))
      common[`--${prefix}-${k}`] = `${String(v)}${unit}`;
  }
  for (const [k, v] of Object.entries(tk.radius)) {
    common[k === 'default' ? '--radius' : `--radius-${k}`] = `${String(v)}px`;
  }
  for (const [k, v] of Object.entries(tk.font.family)) common[`--font-${k}`] = v;
  for (const [k, v] of Object.entries(tk.font.tracking))
    common[`--tracking-${k}`] = `${String(v)}em`;
  for (const [k, v] of Object.entries(tk.elevation)) common[`--elevation-${k}`] = v;
  for (const [k, v] of Object.entries(tk.material)) common[`--material-${k}`] = v;
  const reduced: Record<string, string> = {};
  for (const [k, v] of Object.entries(tk.motion)) {
    if (typeof v === 'number') {
      common[`--motion-${k}`] = `${String(v)}ms`;
      reduced[`--motion-${k}`] = '0ms';
    } else {
      common[`--motion-${k}`] = v;
    }
  }
  return [
    `/* ${HEADER} */\n`,
    block(':root,\n:root[data-theme="dark"]', colourDecls(tk.colour.dark)),
    block(':root[data-theme="light"]', colourDecls(tk.colour.light)),
    block(':root', common),
    `@media (prefers-reduced-motion: reduce) {\n${block(':root', reduced, '  ')}}\n`,
  ].join('\n');
}

function literal(v: Record<string, unknown>, indent: string): string {
  const keys = Object.keys(v).sort();
  const lines = keys.map((k) => {
    const val = v[k];
    const text = isTable(val) ? literal(val, `${indent}  `) : JSON.stringify(val);
    return `${indent}  ${JSON.stringify(k)}: ${text},`;
  });
  return `{\n${lines.join('\n')}\n${indent}}`;
}

export function generateTs(tk: Tokens): string {
  const out = [`// ${HEADER}`, ''];
  out.push(`export const colour = ${literal(tk.colour, '')} as const;`, '');
  out.push('export type ColourToken = keyof typeof colour.dark;', '');
  out.push(`export const space = ${literal(tk.space, '')} as const;`, '');
  out.push(`export const size = ${literal(tk.size, '')} as const;`, '');
  out.push(`export const radius = ${literal(tk.radius, '')} as const;`, '');
  out.push(`export const opacity = ${literal(tk.opacity, '')} as const;`, '');
  out.push(`export const border = ${literal(tk.border, '')} as const;`, '');
  out.push(`export const font = ${literal(tk.font, '')} as const;`, '');
  out.push(`export const elevation = ${literal(tk.elevation, '')} as const;`, '');
  out.push(`export const material = ${literal(tk.material, '')} as const;`, '');
  out.push(`export const motion = ${literal(tk.motion, '')} as const;`, '');
  for (const { prefix, name } of PALETTES) {
    const lines = (['dark', 'light'] as const).map(
      (t) => `  ${JSON.stringify(t)}: ${JSON.stringify(ordered(tk.colour[t], prefix))},`,
    );
    out.push(`export const ${name} = {\n${lines.join('\n')}\n} as const;`, '');
  }
  return out.join('\n');
}

/** A Rust constant name: upper case, `-` → `_`, a leading digit prefixed with `lead` (`S_`). */
function rustName(key: string, lead = 'S_'): string {
  const n = key.toUpperCase().replace(/-/g, '_');
  return /^\d/.test(n) ? `${lead}${n}` : n;
}

/** An f32 literal. */
function rustNumber(v: number): string {
  const s = String(v);
  return /[.e]/.test(s) ? s : `${s}.0`;
}

/** `#RRGGBB[AA]` → `Rgba8([0xRR, 0xGG, 0xBB, 0xAA])`, alpha 0xFF when absent (sRGB-encoded). */
function rustColour(hex: string): string {
  const bytes = [1, 3, 5, 7].map((i) => (i < hex.length ? hex.slice(i, i + 2) : 'FF'));
  return `Rgba8([${bytes.map((b) => `0x${b}`).join(', ')}])`;
}

/** A module of constants: one line for a single constant, else one constant per line. */
function rustModule(name: string, consts: string[], indent: string): string {
  if (consts.length === 1) return `${indent}pub mod ${name} { ${consts[0] ?? ''} }`;
  return [
    `${indent}pub mod ${name} {`,
    ...consts.map((c) => `${indent}    ${c}`),
    `${indent}}`,
  ].join('\n');
}

function rustNumbers(v: Record<string, number>): string[] {
  return Object.keys(v)
    .sort()
    .map((k) => `pub const ${rustName(k)}: f32 = ${rustNumber(v[k] ?? 0)};`);
}

function rustTexts(v: Record<string, string>, lead = 'S_'): string[] {
  return Object.keys(v)
    .sort()
    .map((k) => `pub const ${rustName(k, lead)}: &str = ${JSON.stringify(v[k] ?? '')};`);
}

export function generateRs(tk: Tokens): string {
  const out = [`// ${HEADER}`, '', 'use crate::Rgba8;', ''];
  out.push('pub mod colour {');
  for (const theme of ['dark', 'light'] as const) {
    const c = tk.colour[theme];
    out.push(`    pub mod ${theme} {`, '        use crate::Rgba8;');
    for (const k of Object.keys(c).sort()) {
      out.push(`        pub const ${rustName(k)}: Rgba8 = ${rustColour(c[k] ?? '')};`);
    }
    out.push('    }');
  }
  out.push('}', '');
  for (const { prefix, name } of PALETTES) {
    const constName = name === 'seriesPalette' ? 'SERIES_PALETTE' : 'SEQUENTIAL_RAMP';
    const n = ordered(tk.colour.dark, prefix).length;
    out.push(`pub const ${constName}: [[Rgba8; ${String(n)}]; 2] = [`);
    for (const theme of ['dark', 'light'] as const) {
      const keys = Array.from(
        { length: n },
        (_, i) => `colour::${theme}::${rustName(`${prefix}-${String(i + 1)}`)}`,
      );
      out.push(`    [${keys.join(', ')}],`);
    }
    out.push('];', '');
  }
  out.push(rustModule('space', rustNumbers(tk.space), ''), '');
  out.push(rustModule('size', rustNumbers(tk.size), ''), '');
  out.push(rustModule('radius', rustNumbers(tk.radius), ''), '');
  out.push(rustModule('opacity', rustNumbers(tk.opacity), ''), '');
  out.push(rustModule('border', rustNumbers(tk.border), ''), '');
  out.push('pub mod font {');
  out.push(rustModule('family', rustTexts(tk.font.family), '    '));
  out.push(rustModule('size', rustNumbers(tk.font.size), '    '));
  out.push(rustModule('weight', rustNumbers(tk.font.weight), '    '));
  out.push(rustModule('advance', rustNumbers(tk.font.advance), '    '));
  out.push(rustModule('tracking', rustNumbers(tk.font.tracking), '    '));
  out.push('}', '');
  out.push(rustModule('elevation', rustTexts(tk.elevation, 'E_'), ''), '');
  out.push(rustModule('material', rustTexts(tk.material), ''), '');
  out.push(rustModule('line_height', rustNumbers(tk.font.lineHeight), ''), '');
  const motion = Object.keys(tk.motion)
    .sort()
    .map((k) => {
      const v = tk.motion[k];
      return typeof v === 'number'
        ? `pub const ${rustName(k)}: f32 = ${rustNumber(v)};`
        : `pub const ${rustName(k)}: &str = ${JSON.stringify(v ?? '')};`;
    });
  out.push(rustModule('motion', motion, ''), '');
  return out.join('\n');
}

/** The generated files for the TOML text. Throws `InputError` on invalid tokens. */
export function generate(tomlText: string): { css: string; ts: string; rs: string } {
  const tk = parseTokens(tomlText);
  return { css: generateCss(tk, parse(tomlText)), ts: generateTs(tk), rs: generateRs(tk) };
}

function readText(path: string): string {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return '';
  }
}

/** `--check`: findings for each generated file that differs from what the TOML produces. */
export function checkGenerated(read: (path: string) => string = readText): Finding[] {
  const { css, ts, rs } = generate(readFileSync(TOKENS_TOML, 'utf8'));
  const findings: Finding[] = [];
  for (const [path, want, rel] of [
    [TOKENS_CSS, css, 'src/styles/tokens.css'],
    [TOKENS_TS, ts, 'src/styles/tokens.ts'],
    [TOKENS_RS, rs, 'engine/crates/dash-tokens/src/tokens.rs'],
  ] as const) {
    if (read(path) !== want) {
      findings.push({
        rule: `stale-generated:${rel}`,
        file: rel,
        subject: rel,
        message: 'out of date with design/tokens.toml: run `npm run tokens`',
      });
    }
  }
  return findings;
}

export function main(argv: readonly string[]): number {
  try {
    if (argv.includes('--check')) return report(checkGenerated());
    const { css, ts, rs } = generate(readFileSync(TOKENS_TOML, 'utf8'));
    writeFileSync(TOKENS_CSS, css);
    writeFileSync(TOKENS_TS, ts);
    writeFileSync(TOKENS_RS, rs);
    return 0;
  } catch (e) {
    console.error(`error[tokens] ${e instanceof Error ? e.message : String(e)}`);
    return 2;
  }
}

if (import.meta.main) process.exitCode = main(process.argv.slice(2));
