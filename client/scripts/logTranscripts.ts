/**
 * The paging transcripts of the Explore › Logs e2e (plan #66 Part C §3.13): `logs-paging-1.json`
 * and `logs-paging-2.json` in `e2e/transcripts/`, generated because 1 500 entries are not written
 * by hand. Entry i (0…1 499) is one stream `{app: "paging"}` at 13:00 − 2i s on 2026-01-01, line
 * `paging line <i, 4 digits>`, structured metadata `detected_level` = error, warn, info by i mod 3.
 * The BFF asks page one with `limit` 1001: entries 0…1 000 (1 000 delivered, the cursor at entry
 * 1 000); page two is `(L0, ts₁₀₀₀]`: entries 1 000…1 499, no cursor.
 *
 * `npm run gen:log-transcripts` writes them; `unit:log-transcripts` compares them byte for byte.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const TRANSCRIPT_DIR = fileURLToPath(new URL('../e2e/transcripts/', import.meta.url));

/** 2026-01-01T12:00Z and 13:00Z, in seconds. */
export const L0_S = 1767268800;
export const END_S = L0_S + 3600;
export const PAGE_ENTRIES = 1001;
export const TOTAL_ENTRIES = 1500;
const LEVELS = ['error', 'warn', 'info'] as const;

export interface GeneratedTranscript {
  readonly file: string;
  readonly text: string;
}

/** Nanoseconds as PulsusDB writes them: a decimal string. */
export function ns(ms: number): string {
  return String(BigInt(ms) * 1000000n);
}

/** Entry i's timestamp in ms. */
export function entryMs(i: number): number {
  return (END_S - 2 * i) * 1000;
}

function entry(i: number): unknown[] {
  return [
    ns(entryMs(i)),
    `paging line ${String(i).padStart(4, '0')}`,
    { structuredMetadata: { detected_level: LEVELS[i % 3] } },
  ];
}

function transcript(n: 1 | 2, endMs: number, from: number, to: number): GeneratedTranscript {
  const values = Array.from({ length: to - from }, (_, k) => entry(from + k));
  const body = {
    status: 'success',
    data: {
      resultType: 'streams',
      encodingFlags: ['categorize-labels'],
      result: [{ stream: { app: 'paging' }, values }],
      stats: { streams: 1, entries: values.length },
    },
  };
  const t = {
    name: `logs-paging-${String(n)}`,
    provenance: {
      synthetic: `generated by client/scripts/logTranscripts.ts: page ${String(n)} of 1 500 entries 2 s apart, so the e2e reads two pages`,
    },
    match: {
      method: 'GET',
      paths: ['/api/logs/v1/query_range'],
      query: '{app="paging"}',
      form: { end: ns(endMs), limit: String(PAGE_ENTRIES), direction: 'backward' },
    },
    response: {
      status: 200,
      headers: {
        'Content-Type': 'application/json',
        'X-Pulsus-Query-Id': `fake-logs-paging-${String(n)}`,
      },
      body,
    },
  };
  return { file: `logs-paging-${String(n)}.json`, text: `${JSON.stringify(t, null, 2)}\n` };
}

/** `logs-paging-1.json` and `logs-paging-2.json`, as committed (2-space JSON, final newline). */
export function pagingTranscripts(): readonly GeneratedTranscript[] {
  return [
    transcript(1, END_S * 1000, 0, PAGE_ENTRIES),
    transcript(2, entryMs(PAGE_ENTRIES - 1), PAGE_ENTRIES - 1, TOTAL_ENTRIES),
  ];
}

export function main(): number {
  for (const t of pagingTranscripts()) writeFileSync(join(TRANSCRIPT_DIR, t.file), t.text);
  return 0;
}

if (import.meta.main) process.exitCode = main();
