#![allow(clippy::unwrap_used, clippy::expect_used)]
//! Control block layout v1 against T03 §4.3 and its generated JS mirror (T03-005).

use std::path::Path;

use dash_protocol::layout::{self, REGIONS, off, render_js};

/// `(offset, size)` of each row of the T03 §4.3 table.
fn t03_rows() -> Vec<(u32, u32)> {
    let doc = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../designs/technical/T03-browser-runtime.md");
    let text = std::fs::read_to_string(doc).unwrap();
    let start = text.find("### 4.3").unwrap();
    text[start..]
        .lines()
        .skip_while(|l| !l.starts_with('|'))
        .take_while(|l| l.starts_with('|'))
        .skip(2)
        .map(|l| {
            let cells: Vec<&str> = l.trim_matches('|').split('|').map(str::trim).collect();
            let offset =
                u32::from_str_radix(cells[0].trim_matches('`').trim_start_matches("0x"), 16)
                    .unwrap();
            let size = match cells[1].strip_suffix(" KiB") {
                Some(k) => k.parse::<u32>().unwrap() * 1024,
                None => cells[1].parse().unwrap(),
            };
            (offset, size)
        })
        .collect()
}

#[test]
fn layout_regions_match_t03() {
    let rows = t03_rows();
    assert_eq!(rows.len(), 12);
    let ours: Vec<(u32, u32)> = REGIONS.iter().map(|r| (r.offset, r.size)).collect();
    assert_eq!(ours, rows);
    let names: Vec<&str> = REGIONS.iter().map(|r| r.name).collect();
    assert_eq!(
        names,
        [
            "header",
            "frame_clock",
            "input_head",
            "input_tail",
            "chords",
            "ui_core",
            "core_ui",
            "copy",
            "counters",
            "input_data",
            "ui_core_data",
            "core_ui_data"
        ]
    );
    let end = REGIONS.iter().map(|r| r.offset + r.size).max().unwrap();
    assert_eq!(end, layout::CB_SIZE);
    assert_eq!(layout::CB_SIZE, 0x40000);
    assert_eq!(layout::CB_ALIGN, 64);
    assert_eq!(layout::RING_BYTES, 0x10000);
}

