#[test]
fn layout_fields_aligned_and_inside() {
    let fs = fields();
    for (name, at, size, align, region) in &fs {
        assert_eq!(at % align, 0, "{name} at {at:#x} not {align}-aligned");
        let r = REGIONS
            .iter()
            .find(|r| r.offset <= *at && at + size <= r.offset + r.size)
            .unwrap_or_else(|| panic!("{name} at {at:#x}+{size} is in no region"));
        assert_eq!(r.name, *region, "{name}");
    }
    for (i, a) in fs.iter().enumerate() {
        for b in &fs[i + 1..] {
            assert!(
                a.1 + a.2 <= b.1 || b.1 + b.2 <= a.1,
                "{} overlaps {}",
                a.0,
                b.0
            );
        }
    }
    const { assert!(off::FS_RECENT_CPU + 1024 <= 0x5400) };
    let js = render_js();
    let offs = js
        .lines()
        .filter(|l| l.starts_with("export const OFF_"))
        .count();
    assert_eq!(
        offs,
        fs.len(),
        "every off const is listed here and in render_js"
    );
}

#[test]
fn layout_js_exact() {
    let a = render_js();
    assert_eq!(a, render_js());
    assert!(a.is_ascii());
    assert!(a.ends_with(";\n"));
    assert!(!a.contains('\r'));
    let mut lines = a.lines();
    assert_eq!(
        lines.next(),
        Some("// Generated by `cargo xtask gen` from dash-protocol. Do not edit.")
    );
    let exports: Vec<&str> = lines.collect();
    assert!(
        exports.iter().all(|l| l.starts_with("export const ")),
        "{exports:?}"
    );
    for want in [
        "export const LAYOUT_VERSION = 1;",
        "export const OFF_INPUT_HEAD = 128;",
        "export const STATUS_TIER_T1 = 1;",
        "export const RETRY_T2 = 256;",
        "export const CAP_DPCB = 32;",
    ] {
        assert!(exports.contains(&want), "missing {want}");
    }
    // 5 scalars + 21 offsets + 6 capability bits + 6 status codes, one export each.
    assert_eq!(exports.len(), 5 + 21 + 6 + 6);
    let mut names: Vec<&str> = exports
        .iter()
        .map(|l| l["export const ".len()..].split(' ').next().unwrap())
        .collect();
    names.sort_unstable();
    names.dedup();
    assert_eq!(names.len(), exports.len(), "duplicate export");
}
