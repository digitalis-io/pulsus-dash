#!/usr/bin/env bash
# ci:go-licenses (T18-026, D3): every module linked into pulsus-dash must carry a licence on the
# AGPL-3.0-compatible allowlist below; GPL-2.0-only, source-available licences and any unrecognised
# licence fail. Writes build/THIRD_PARTY_NOTICES.txt from the saved licence and notice files, then
# appends the "Data" section of the bundled geo datasets (tools/geo/build.py --notices).
#
# Usage:
#   go-licenses.sh
#       the gate: check ./cmd/pulsus-dash, then write the notices file
#   go-licenses.sh --check DIR PATTERN IGNORE [EXTRA]
#       only the licence check, with this script's allowlist (plus the comma-separated EXTRA
#       licences, if given), of PATTERN in module directory DIR, ignoring module IGNORE. The
#       self-test (check-go-licenses-fixture.sh) uses it, so the gate and its test share one list.
# Run from any directory inside the repository.
# Exit: 0 every licence allowed (and the notices file written), 2 usage, non-zero otherwise.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
GL="$ROOT/build/bin/go-licenses"
LICENCES=MIT,BSD-2-Clause,BSD-3-Clause,Apache-2.0,ISC,MPL-2.0,LGPL-2.1,LGPL-3.0
NOTICES="$ROOT/build/THIRD_PARTY_NOTICES.txt"

# 1. The pinned tool (server/go.mod tool directive).
build_tool() {
  go -C "$ROOT/server" build -o "$GL" github.com/google/go-licenses/v2
}

# 2. The licence check (the standard library is found through GOROOT).
# licence_check DIR PATTERN IGNORE [EXTRA]
licence_check() {
  local allowed=$LICENCES
  if [ -n "${4:-}" ]; then allowed="$allowed,$4"; fi
  GOROOT="$(go env GOROOT)"
  export GOROOT
  (cd "$1" && "$GL" check "$2" --ignore "$3" --allowed_licenses="$allowed")
}

if [ "${1:-}" = "--check" ]; then
  if [ $# -lt 4 ] || [ $# -gt 5 ]; then
    echo "usage: go-licenses.sh --check DIR PATTERN IGNORE [EXTRA]" >&2
    exit 2
  fi
  [ -x "$GL" ] || build_tool
  licence_check "$2" "$3" "$4" "${5:-}"
  exit 0
fi
if [ $# -ne 0 ]; then
  echo "usage: go-licenses.sh | go-licenses.sh --check DIR PATTERN IGNORE [EXTRA]" >&2
  exit 2
fi

build_tool
licence_check "$ROOT/server" ./cmd/pulsus-dash github.com/digitalis-io/pulsus-dash

# 3. Save the licence and notice files of those modules.
rm -rf "$ROOT/build/licenses"
(cd "$ROOT/server" && "$GL" save ./cmd/pulsus-dash --ignore github.com/digitalis-io/pulsus-dash --save_path="$ROOT/build/licenses" --force)

# 4. The notices file: a header, then each licence or notice file in byte order.
{
  echo "Pulsus Dash third-party notices"
  echo "Generated by make go-licenses from the Go modules linked into pulsus-dash."
  echo
  (cd "$ROOT/build/licenses" && find . -type f -print0) |
    LC_ALL=C sort -z |
    while IFS= read -r -d '' f; do
      base=${f##*/}
      if grep -qiE '^(LICEN[CS]E|COPYING|NOTICE)([._-].*)?$' <<<"$base"; then
        echo "== ${f#./} =="
        cat "$ROOT/build/licenses/$f"
        echo
      fi
    done
} >"$NOTICES"

# 5. At least one module's licence must be in it.
if ! grep -q '^== ' "$NOTICES"; then
  echo "notices file is empty"
  exit 1
fi

# 6. The "Data" section: the bundled geo datasets (T24 §5.13).
python3 -I "$ROOT/tools/geo/build.py" --notices >>"$NOTICES"
echo "go-licenses: every module allowed; wrote build/THIRD_PARTY_NOTICES.txt"
