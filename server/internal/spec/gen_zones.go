//go:build ignore

// gen_zones writes zones_gen.go: the zone names of the zoneinfo.zip of the toolchain running it
// ($(go env GOROOT)/lib/time/zoneinfo.zip, the file time/tzdata embeds). Run go generate
// ./internal/spec after a Go upgrade; TestEmbeddedZonesMatchToolchain fails until then.
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"strings"
)

func main() {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		log.Fatalf("go env GOROOT: %v", err)
	}
	zr, err := zip.OpenReader(filepath.Join(strings.TrimSpace(string(out)), "lib", "time", "zoneinfo.zip"))
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = zr.Close() }()
	var names []string
	for _, f := range zr.File {
		if !strings.HasSuffix(f.Name, "/") {
			names = append(names, f.Name)
		}
	}
	slices.Sort(names)
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_zones.go from the toolchain's lib/time/zoneinfo.zip; DO NOT EDIT.\n\n")
	b.WriteString("package spec\n\n")
	b.WriteString("// embeddedZones are the zone names of this build (zones.go zoneExists).\n")
	b.WriteString("var embeddedZones = map[string]struct{}{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: {},\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("zones_gen.go", src, 0o644); err != nil { //nolint:gosec // a source file
		log.Fatal(err)
	}
}
